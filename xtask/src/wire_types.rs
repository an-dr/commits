//! `ipc/ts/bones-messages.ts`: TypeScript names for the bones messages Commits
//! speaks, generated from the engine's wire format specification so a
//! renumbered action or a renamed field reaches the codec as a type error.
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use serde_json::Value;

use crate::{parse_options, Result};

/// Where the generated module lives, relative to the repository root.
pub const OUTPUT: &str = "ipc/ts/bones-messages.ts";
const SPEC: &str = "vendor/bones/wit/wire-format.json";
/// Topic families and direct-send endpoints the app's codec covers.
const TOPIC_PREFIXES: [&str; 4] = ["web/", "desktop/", "os/", "upgrader/"];
const ENDPOINTS: [&str; 1] = ["web"];

pub fn run(args: &[String]) -> Result {
    parse_options(args, &[])?;
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).parent().unwrap();
    fs::write(root.join(OUTPUT), generate(root)?)?;
    println!("Written {OUTPUT}");
    Ok(())
}

/// The module text for the specification in the checkout at `root`.
pub fn generate(root: &Path) -> Result<String> {
    let spec: Value = serde_json::from_str(&fs::read_to_string(root.join(SPEC))?)?;
    let mut out = String::from(
        "// Generated by `cargo xtask wire-types` from vendor/bones/wit/wire-format.json.\n\
         // Do not edit; regenerate after updating bones.\n",
    );
    let groups = spec["groups"].as_array().ok_or("wire format has no groups")?;
    for entry in groups.iter().flat_map(|group| group["entries"].as_array().into_iter().flatten()) {
        let names = strings(&entry["topics"])
            .filter(|topic| TOPIC_PREFIXES.iter().any(|prefix| topic.starts_with(prefix)))
            .map(|topic| type_name(&topic))
            .chain(
                strings(&entry["endpoints"])
                    .filter(|endpoint| ENDPOINTS.contains(&endpoint.as_str()))
                    .map(|endpoint| format!("{}Send", type_name(&endpoint))),
            );
        for name in names {
            write_entry(&mut out, &name, &entry["payload"])?;
        }
    }
    Ok(out)
}

fn write_entry(out: &mut String, name: &str, payload: &Value) -> Result {
    let fields = payload["fields"].as_array().map(Vec::as_slice).unwrap_or_default();
    let union = &payload["union"];
    if union.is_null() {
        writeln!(out, "\nexport interface {name} {{")?;
        for field in fields {
            let ty = field["type"].as_str().ok_or("list fields are not supported")?;
            writeln!(out, "  readonly {}: {};", field["name"].as_str().unwrap_or_default(), ts_type(ty)?)?;
        }
        writeln!(out, "}}")?;
    }
    let variants = union["variants"].as_array().map(Vec::as_slice).unwrap_or_default();
    let variant_fields = variants
        .iter()
        .flat_map(|variant| variant["fields"].as_array().into_iter().flatten());
    for field in fields.iter().chain(variant_fields) {
        if let Some(values) = field["values"].as_array() {
            let field_name = pascal(field["name"].as_str().unwrap_or_default());
            write_constants(out, &format!("{name}{field_name}"), values, "value")?;
        }
    }
    if !variants.is_empty() {
        write_constants(out, &format!("{name}Tag"), variants, "tag")?;
    }
    Ok(())
}

/// `export const <name> = { camelName: number, ... } as const;`
fn write_constants(out: &mut String, name: &str, items: &[Value], number_key: &str) -> Result {
    writeln!(out, "\nexport const {name} = {{")?;
    for item in items {
        let number = item[number_key].as_u64().ok_or("value without a number")?;
        writeln!(out, "  {}: {number},", camel(item["name"].as_str().unwrap_or_default()))?;
    }
    writeln!(out, "}} as const;")?;
    Ok(())
}

fn strings(value: &Value) -> impl Iterator<Item = String> + '_ {
    value
        .as_array()
        .into_iter()
        .flatten()
        .filter_map(|item| item.as_str().map(str::to_owned))
}

fn ts_type(wire: &str) -> Result<&'static str> {
    Ok(match wire {
        "u8" | "u16" | "u32" | "i32" | "f32" => "number",
        "bool" => "boolean",
        "str" | "str-rest" => "string",
        "blob" | "rest" => "Uint8Array",
        other => return Err(format!("unsupported wire type {other}").into()),
    })
}

fn words(text: &str) -> impl Iterator<Item = String> + '_ {
    text.split(['/', '-', '_', ' '])
        .filter(|word| !word.is_empty())
        .map(|word| {
            let lower = word.to_ascii_lowercase();
            let mut chars = lower.chars();
            chars.next().map_or_else(String::new, |first| first.to_ascii_uppercase().to_string() + chars.as_str())
        })
}

/// `web/page-message` → `WebPageMessage`.
fn type_name(topic: &str) -> String {
    words(topic).collect()
}

fn pascal(text: &str) -> String {
    words(text).collect()
}

/// `open URL` → `openUrl`, `up-to-date` → `upToDate`.
fn camel(text: &str) -> String {
    let pascal = pascal(text);
    let mut chars = pascal.chars();
    chars.next().map_or_else(String::new, |first| first.to_ascii_lowercase().to_string() + chars.as_str())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn committed_module_matches_the_pinned_wire_format() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).parent().unwrap();
        let committed = fs::read_to_string(root.join(OUTPUT)).unwrap().replace("\r\n", "\n");
        assert!(
            committed == generate(root).unwrap(),
            "{OUTPUT} is stale; run cargo xtask wire-types"
        );
    }

    #[test]
    fn names_follow_typescript_conventions() {
        assert_eq!(type_name("web/page-message"), "WebPageMessage");
        assert_eq!(camel("open URL"), "openUrl");
        assert_eq!(camel("up-to-date"), "upToDate");
        assert_eq!(camel("last-applied"), "lastApplied");
        assert_eq!(pascal("source_kind"), "SourceKind");
    }
}
